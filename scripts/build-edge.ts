/**
 * Build the Supabase Edge Function payload:
 *   supabase/functions/graphql/dataset.json  – compact copy of the artifacts
 *   supabase/functions/graphql/schema.ts     – the SDL as a module
 *   supabase/functions/graphql/_bundle.js    – executor + resolvers + graphql-js
 *
 * Run with `npm run edge:build`. The bundle is self-contained so the deploy
 * never depends on files outside the function directory.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadFromArtifacts } from "../api/src/sources.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "supabase/functions/graphql");
mkdirSync(OUT, { recursive: true });

const dataset = loadFromArtifacts();

// Drop fields no resolver reads, and cap event evidence so the payload stays small.
const VIDEO_KEYS = [
  "id", "platform", "platform_id", "url", "creator_handle", "creator_display_name", "creator_followers",
  "creator_verified", "posted_at", "views", "likes", "shares", "comments", "interactions", "title",
  "caption", "caption_language", "transcript", "transcript_language", "on_screen_text", "visual_tags",
  "platform_format", "format", "duration_seconds", "thumbnail_url", "is_french", "party_signals",
] as const;
const videos = dataset.videos.map((video: any) => Object.fromEntries(VIDEO_KEYS.filter((key) => key in video).map((key) => [key, video[key]])));
const events = {
  ...dataset.events,
  events: dataset.events.events.map((event: any) => ({ ...event, evidence: (event.evidence ?? []).slice(0, 2) })),
};

const payload = {
  candidates: dataset.candidates,
  videos,
  stance: dataset.stance,
  events,
  facts: dataset.facts,
  origin: { videos: "bundled", stance: "bundled", events: "bundled", facts: "bundled" },
};
writeFileSync(resolve(OUT, "dataset.json"), JSON.stringify(payload));
writeFileSync(
  resolve(OUT, "schema.ts"),
  `// Generated by scripts/build-edge.ts\nexport const SDL = ${JSON.stringify(readFileSync(resolve(ROOT, "api/schema.graphql"), "utf8"))};\n`,
);

execFileSync(
  "npx",
  [
    "--yes", "esbuild", resolve(ROOT, "api/src/edge-handler.ts"),
    "--bundle", "--format=esm", "--platform=neutral", "--target=es2022",
    "--define:process.env.NODE_ENV=\"production\"",
    `--outfile=${resolve(OUT, "_bundle.js")}`,
    "--log-level=warning",
  ],
  { stdio: "inherit", cwd: ROOT },
);

const size = (name: string) => (readFileSync(resolve(OUT, name)).length / 1024).toFixed(0);
console.log(`edge build: dataset ${size("dataset.json")} kB · schema ${size("schema.ts")} kB · bundle ${size("_bundle.js")} kB`);

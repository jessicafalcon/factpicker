/**
 * Generates supabase/migrations/0002_seed.sql from the TypeScript dictionaries,
 * so the database and the matcher can never drift apart.
 *
 *   npm run seed:sql
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { CANDIDATES } from "../supabase/functions/_shared/candidates.ts";
import { COMMUNITIES } from "../supabase/functions/_shared/communities.ts";

const q = (value: string | null | undefined) =>
  value === null || value === undefined ? "null" : `'${value.replace(/'/g, "''")}'`;

const arr = (values: string[]) =>
  values.length === 0
    ? "'{}'::text[]"
    : `array[${values.map((value) => q(value)).join(", ")}]::text[]`;

const candidateRows = CANDIDATES.map(
  (c) =>
    `  (${q(c.id)}, ${q(c.name)}, ${q(c.party)}, ${q(c.partyShort)}, ${q(c.status)}, ${q(c.tier)}, ` +
    `${q(c.statusNote)}, ${q(c.slogan)}, ${arr(c.aliases)}, ${arr(c.weakAliases)}, ${arr(c.partySignals)}, ` +
    `${arr(c.communities)}, now())`,
).join(",\n");

const communityRows = COMMUNITIES.map(
  (c) =>
    `  (${q(c.id)}, ${q(c.name)}, ${q(c.type)}, ${q(c.alignment)}, ${arr(c.aliases)}, ${arr(c.backs)}, ${q(c.notes)})`,
).join(",\n");

const sql = `-- Generated by scripts/make-seed.ts — do not edit by hand.
-- Source: fr.wikipedia "Candidatures à l'élection présidentielle française de 2027"
-- (revision 31 Oct 2026) and the late-Oct 2026 first-round polling table.

insert into public.candidates
  (id, name, party, party_short, status, tier, status_note, slogan, aliases, weak_aliases, party_signals, communities, status_checked_at)
values
${candidateRows}
on conflict (id) do update set
  name          = excluded.name,
  party         = excluded.party,
  party_short   = excluded.party_short,
  status        = excluded.status,
  tier          = excluded.tier,
  status_note   = excluded.status_note,
  slogan        = excluded.slogan,
  aliases       = excluded.aliases,
  weak_aliases  = excluded.weak_aliases,
  party_signals = excluded.party_signals,
  communities   = excluded.communities;

insert into public.communities (id, name, type, alignment, aliases, backs, notes)
values
${communityRows}
on conflict (id) do update set
  name      = excluded.name,
  type      = excluded.type,
  alignment = excluded.alignment,
  aliases   = excluded.aliases,
  backs     = excluded.backs,
  notes     = excluded.notes;
`;

mkdirSync("supabase/migrations", { recursive: true });
writeFileSync("supabase/migrations/0002_seed.sql", sql);
console.log(
  `Wrote supabase/migrations/0002_seed.sql: ${CANDIDATES.length} candidates, ${COMMUNITIES.length} communities.`,
);
